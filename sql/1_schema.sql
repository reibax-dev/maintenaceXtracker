CREATE TABLE IF NOT EXISTS public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    rol VARCHAR(10) NOT NULL DEFAULT 'user'
        CHECK (rol IN ('user', 'admin')),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.equipos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    centro VARCHAR(160) NOT NULL,
    instalacion VARCHAR(180) NOT NULL,
    maquina VARCHAR(180) NOT NULL,
    elemento VARCHAR(180) NOT NULL DEFAULT '',
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT equipos_ubicacion_unica
        UNIQUE (centro, instalacion, maquina, elemento)
);

CREATE TABLE IF NOT EXISTS public.partes_trabajo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ot_origen BIGINT UNIQUE,
    fecha DATE NOT NULL,
    turno VARCHAR(10) NOT NULL
        CHECK (turno IN ('manana', 'tarde', 'noche')),
    grupo_responsable VARCHAR(2) NOT NULL
        CHECK (grupo_responsable IN ('1', '2', '3', '4', '5', 'D', 'JA')),
    hubo_parada BOOLEAN NOT NULL,
    causa VARCHAR(24) NOT NULL
        CHECK (causa IN ('AVERIA_ELECTRICA', 'TRABAJO_ELECTRICO')),
    trabajo_realizado TEXT NOT NULL,
    equipo_id BIGINT NOT NULL REFERENCES public.equipos(id) ON DELETE RESTRICT,
    creado_por_usuario_id BIGINT REFERENCES public.usuarios(id) ON DELETE SET NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS partes_trabajo_fecha_idx
    ON public.partes_trabajo (fecha DESC);
CREATE INDEX IF NOT EXISTS partes_trabajo_equipo_idx
    ON public.partes_trabajo (equipo_id);
